#!/usr/bin/env python3
"""Fails unless the LibRaw that CI links on Windows is the version vendored in this repository (RFC-0038 A4).

The Rust FFI structs are generated by bindgen from the vendored header (app/src-tauri/vendor/rsraw-sys/LibRaw/libraw/
libraw_version.h, 0.21.3), and the Windows build links the vcpkg port instead of compiling that source. If the two
versions differ the struct layouts can disagree and writes land on the wrong offsets (this happened once with 0.22.1,
see ci.yml). Checking it also makes "the LibRaw source is the vendored 0.21.3 plus the vcpkg port's patches" a checked
claim rather than a hope.

    python3 scripts/check_libraw_version.py "$VCPKG_INSTALLATION_ROOT/installed/x64-windows-static-md/include/libraw/libraw_version.h"
    python3 scripts/check_libraw_version.py --self-test

Standard library only."""
import re
import sys
import tempfile
import unittest
from pathlib import Path

VENDORED = Path(__file__).resolve().parent.parent / "app/src-tauri/vendor/rsraw-sys/LibRaw/libraw/libraw_version.h"


def version(header_text):
    """(major, minor, patch) from the three LIBRAW_*_VERSION defines, or None if any is missing."""
    found = [re.search(rf"^\s*#\s*define\s+LIBRAW_{n}_VERSION\s+(\d+)\b", header_text, re.M) for n in ("MAJOR", "MINOR", "PATCH")]
    return tuple(int(m.group(1)) for m in found) if all(found) else None


def check(installed_path, vendored_path=VENDORED):
    """Returns (ok, message)."""
    vendored = version(Path(vendored_path).read_text(encoding="utf-8", errors="replace"))
    if vendored is None:
        return False, f"cannot read the vendored LibRaw version from {vendored_path}"
    p = Path(installed_path)
    if not p.is_file():
        return False, f"the installed LibRaw header is not at {p}: did the vcpkg step install libraw, and is the path right?"
    installed = version(p.read_text(encoding="utf-8", errors="replace"))
    if installed is None:
        return False, f"cannot read a LibRaw version from {p}"
    if installed != vendored:
        return False, f"the vcpkg LibRaw is {'.'.join(map(str, installed))} but the vendored one is {'.'.join(map(str, vendored))}: the bindgen struct layouts may not match"
    return True, f"LibRaw {'.'.join(map(str, installed))}: the installed library and the vendored header agree"


class SelfTest(unittest.TestCase):
    HEADER = "#define LIBRAW_MAJOR_VERSION {}\n#define LIBRAW_MINOR_VERSION {}\n#define LIBRAW_PATCH_VERSION {}\n#define LIBRAW_VERSION_TAIL Release\n"

    def write(self, d, name, v):
        path = Path(d) / name
        path.write_text(self.HEADER.format(*v))
        return path

    def test_equal_versions_pass_and_any_difference_fails(self):
        with tempfile.TemporaryDirectory() as d:
            vendored = self.write(d, "v.h", (0, 21, 3))
            self.assertTrue(check(self.write(d, "a.h", (0, 21, 3)), vendored)[0])
            for other in ((0, 22, 1), (0, 21, 4), (1, 21, 3)):
                ok, msg = check(self.write(d, "b.h", other), vendored)
                self.assertFalse(ok)
                self.assertIn("vendored", msg)

    def test_a_missing_or_unreadable_header_fails_with_a_reason(self):
        with tempfile.TemporaryDirectory() as d:
            vendored = self.write(d, "v.h", (0, 21, 3))
            self.assertIn("not at", check(Path(d) / "nope.h", vendored)[1])
            (Path(d) / "junk.h").write_text("nothing here")
            self.assertIn("cannot read", check(Path(d) / "junk.h", vendored)[1])

    def test_the_real_vendored_header_parses(self):
        self.assertEqual(version(VENDORED.read_text()), (0, 21, 3))


def main(argv):
    if "--self-test" in argv:
        return 0 if unittest.TextTestRunner(verbosity=2).run(unittest.defaultTestLoader.loadTestsFromTestCase(SelfTest)).wasSuccessful() else 1
    if len(argv) != 1:
        print(__doc__, file=sys.stderr)
        return 2
    ok, message = check(argv[0])
    print(message, file=sys.stderr if not ok else sys.stdout)
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
