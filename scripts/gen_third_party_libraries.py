#!/usr/bin/env python3
"""Regenerates THIRD_PARTY_LIBRARIES.md: the Rust crates compiled into the app and the npm packages bundled into
its frontend, with the licence each declares. Run from anywhere:  python3 scripts/gen_third_party_libraries.py

Also writes licenses/, the licence texts the installer ships beside this file (see licence_files() below).

Rust: `cargo tree -e normal --target all` (what the app links on any platform; build scripts, dev dependencies and
proc-macros do not ship). npm: the non-dev entries of app/package-lock.json (what Vite bundles).
The hand-written section at the top of the output is the TEXT constant below; edit it there, not in the output."""
import hashlib, json, re, shutil, subprocess, sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "THIRD_PARTY_LIBRARIES.md"
LICENSES = ROOT / "licenses"
# The one text committed by hand: the Creative Commons legal code for the Lensfun database, downloaded once from
# https://creativecommons.org/licenses/by-sa/3.0/legalcode.txt (22,240 bytes, 2026-11-15). The generator checks it, never fetches it.
CC_BY_SA_SHA256 = "3f941b3b89cf7b8370ceb83cc76d2120d471b58735d8ca60238a751a48d7f72f"

TEXT = """# Third-party libraries

The code libraries that Emulsion is built from, and the licence each one declares. The AI models that ship with the
app are covered separately in [THIRD_PARTY_NOTICES.md](THIRD_PARTY_NOTICES.md). Everything below is open source. The
licence texts that carry conditions beyond "keep the notice" are in the `licenses/` folder installed beside this file:
LibRaw (LGPL-2.1, CDDL-1.0 and its copyright file), the `lensfun` crate (LGPL-3.0 and GPL-3.0, with its NOTICE), the
Lensfun lens database (CC-BY-SA 3.0), MPL-2.0 and CDLA-Permissive-2.0; `licenses/README.txt` says which file is which.
For every other library the full text is in its own source distribution (the `LICENSE` files next to its code on
crates.io or npm), and the MIT, Apache-2.0 and BSD texts that most of them use are reproduced in THIRD_PARTY_NOTICES.md.

This file is generated by `scripts/gen_third_party_libraries.py`; do not edit the lists by hand.

## Components with conditions beyond "keep the notice"

| Component | What it is here | Licence | Where its terms are |
| --- | --- | --- | --- |
| LibRaw | Decodes RAW files; compiled into the app as a static library (`app/src-tauri/vendor/rsraw-sys`, patched, see its `PATCH.md`; on Windows a vcpkg build of the same library) | LGPL-2.1 **or** CDDL-1.0, at the user's choice; copyright LibRaw LLC | `licenses/LibRaw-COPYRIGHT`, `LibRaw-LICENSE.LGPL`, `LibRaw-LICENSE.CDDL` (copies of the files in `app/src-tauri/vendor/rsraw-sys/LibRaw/`) |
| `lensfun` crate | Lens distortion, vignetting and chromatic-aberration correction; a pure-Rust port of Lensfun, compiled into the app | LGPL-3.0-or-later; copyright the Lensfun contributors and David Veszelovszki | `licenses/lensfun-LICENSE-LGPL-3.0`, `lensfun-LICENSE-GPL-3.0`, `lensfun-NOTICE` (the crate's own files) |
| Lensfun lens database | The lens calibration data (XML) the `lensfun` crate embeds and the app reads | CC-BY-SA 3.0 Unported; the Lensfun community | `licenses/CC-BY-SA-3.0.txt`; <https://creativecommons.org/licenses/by-sa/3.0/> |
| `cssparser`, `dtoa-short`, `selectors` | CSS parsing, pulled in by Tauri's HTML handling (`tauri-utils`, `wry`) | MPL-2.0 | `licenses/MPL-2.0.txt` (`selectors` ships no licence file of its own; its `Cargo.toml` declares MPL-2.0) |
| `dyn-eq` | Small helper used by `tract`, the ONNX inference engine | MPL-2.0 | `licenses/MPL-2.0.txt` |
| `option-ext` | Small helper used by `dirs`, which finds the app-data folder | MPL-2.0 | `licenses/MPL-2.0.txt` |
| `webpki-root-certs` | Root certificates `reqwest` uses to verify HTTPS when downloading models | CDLA-Permissive-2.0 | `licenses/CDLA-Permissive-2.0.txt` |
| Vendored `rsraw`, `rsraw-sys` | Safe wrapper and build glue around LibRaw, patched in this repository | MIT (upstream <https://github.com/hexilee/rsraw>) | `app/src-tauri/vendor/*/Cargo.toml` |

The MPL-2.0 files are used unmodified. MPL-2.0 is a file-level licence: changes to those files would have to be published under it, and nothing else in Emulsion is affected.

Emulsion's own code is under the licence in the repository's `LICENSE` file.
"""


def rust_libs():
    out = subprocess.run(
        ["cargo", "tree", "-e", "normal", "--target", "all", "--prefix", "none", "--format", "{p}|{l}"],
        cwd=ROOT / "app" / "src-tauri", capture_output=True, text=True, check=True).stdout
    libs = {}
    for line in out.splitlines():
        line = line.replace(" (*)", "")
        if "(proc-macro)" in line:
            continue
        m = re.match(r"(\S+) v(\S+?)(?: \([^)]*\))?\|(.*)$", line)
        if not m or "emulsion" == m.group(1):
            continue
        name, version, lic = m.groups()
        libs[(name, version)] = lic.strip() or "(none declared)"
    return libs


def npm_libs():
    lock = json.loads((ROOT / "app" / "package-lock.json").read_text())
    libs = {}
    for path, meta in lock.get("packages", {}).items():
        if not path or meta.get("dev") or meta.get("devOptional"):
            continue
        name = path.split("node_modules/")[-1]
        libs[(name, meta.get("version", "?"))] = meta.get("license", "(none declared)")
    return libs


def section(title, libs):
    by_lic = defaultdict(list)
    for (name, version), lic in sorted(libs.items()):
        by_lic[lic].append(f"{name} {version}")
    lines = [f"## {title} ({len(libs)})", ""]
    for lic, items in sorted(by_lic.items(), key=lambda kv: (-len(kv[1]), kv[0])):
        lines += [f"### {lic} ({len(items)})", "", ", ".join(items), ""]
    return "\n".join(lines)


def cargo_packages():
    out = subprocess.run(["cargo", "metadata", "--format-version", "1", "--locked"], cwd=ROOT / "app" / "src-tauri",
                         capture_output=True, text=True, check=True).stdout
    pk = defaultdict(list)
    for p in json.loads(out)["packages"]:
        pk[p["name"]].append(Path(p["manifest_path"]).parent)
    return pk


def squash(text):
    """The text without line breaks or runs of spaces, and with http and https alike: one MPL-2.0 file spells the
    Exhibit A address with https and the others with http, and that is the only difference."""
    return " ".join(text.split()).replace("https://", "http://")


README = """Licence texts that ship with Emulsion (generated by scripts/gen_third_party_libraries.py; do not edit by hand).
THIRD_PARTY_LIBRARIES.md, installed beside this folder, says which library each one belongs to.

LibRaw-COPYRIGHT, LibRaw-LICENSE.LGPL, LibRaw-LICENSE.CDDL
    LibRaw, the RAW decoder: copyright LibRaw LLC; offered under the LGPL-2.1 or the CDDL-1.0, at the user's choice.
lensfun-LICENSE-LGPL-3.0, lensfun-LICENSE-GPL-3.0, lensfun-NOTICE
    The `lensfun` crate (lens corrections): LGPL-3.0-or-later, with the GPL-3.0 it refers to, and the crate's own notice.
CC-BY-SA-3.0.txt
    The Lensfun lens database (the lens calibration data), Creative Commons Attribution-ShareAlike 3.0 Unported,
    by the Lensfun community. The database is used unmodified.
MPL-2.0.txt
    cssparser, dtoa-short, dyn-eq, option-ext and selectors (Mozilla Public License 2.0). These crates are used
    unmodified. The selectors crate carries no licence file of its own; its Cargo.toml declares MPL-2.0.
CDLA-Permissive-2.0.txt
    webpki-root-certs (the root certificates used to check HTTPS), Community Data License Agreement Permissive 2.0.

The MIT, Apache-2.0 and BSD texts that most other libraries use are in THIRD_PARTY_NOTICES.md.
"""


def licence_files():
    """Writes licenses/: copies of the licence texts of the components with conditions beyond "keep the notice".
    Everything is copied from the files that are really in the build (the vendored LibRaw, the crates Cargo resolved), so
    the folder follows a version bump; CC-BY-SA-3.0.txt is the one committed by hand and is checked against its pinned hash."""
    cc = LICENSES / "CC-BY-SA-3.0.txt"
    if not cc.is_file() or hashlib.sha256(cc.read_bytes()).hexdigest() != CC_BY_SA_SHA256:
        raise SystemExit(f"{cc} is missing or is not the pinned CC-BY-SA 3.0 legal code (see CC_BY_SA_SHA256)")
    pk = cargo_packages()
    one = lambda name: pk[name][0]  # these crates occur once in the lockfile (checked below for lensfun)
    assert len(pk["lensfun"]) == 1, "more than one lensfun in the lockfile"
    libraw = ROOT / "app" / "src-tauri" / "vendor" / "rsraw-sys" / "LibRaw"
    wanted = {
        "LibRaw-COPYRIGHT": libraw / "COPYRIGHT",
        "LibRaw-LICENSE.LGPL": libraw / "LICENSE.LGPL",
        "LibRaw-LICENSE.CDDL": libraw / "LICENSE.CDDL",
        "lensfun-LICENSE-LGPL-3.0": one("lensfun") / "LICENSE-LGPL-3.0",
        "lensfun-LICENSE-GPL-3.0": one("lensfun") / "LICENSE-GPL-3.0",
        "lensfun-NOTICE": one("lensfun") / "NOTICE",
        "MPL-2.0.txt": one("cssparser") / "LICENSE",
        "CDLA-Permissive-2.0.txt": one("webpki-root-certs") / "LICENSE",
    }
    # One MPL-2.0 text stands for all of them: the crates that carry a file must carry the same text.
    for name, fname in (("dtoa-short", "LICENSE"), ("dyn-eq", "LICENSE"), ("option-ext", "LICENSE.txt")):
        if squash((one(name) / fname).read_text()) != squash(wanted["MPL-2.0.txt"].read_text()):
            raise SystemExit(f"{name}'s {fname} differs from cssparser's MPL-2.0 text: ship both")
    LICENSES.mkdir(exist_ok=True)
    for name, src in wanted.items():
        if not src.is_file():
            raise SystemExit(f"missing licence source {src}")
        shutil.copyfile(src, LICENSES / name)
    (LICENSES / "README.txt").write_text(README)
    extra = sorted(p.name for p in LICENSES.iterdir() if p.name not in wanted and p.name not in ("README.txt", "CC-BY-SA-3.0.txt"))
    if extra:
        raise SystemExit(f"licenses/ holds files the generator does not know: {', '.join(extra)}")
    return len(wanted) + 2


def main():
    text = TEXT + "\n" + section("Rust crates", rust_libs()) + "\n" + section("JavaScript packages", npm_libs())
    OUT.write_text(text.rstrip() + "\n")
    print(f"wrote {OUT} ({len(text.splitlines())} lines) and {licence_files()} files in {LICENSES}")


if __name__ == "__main__":
    sys.exit(main())
