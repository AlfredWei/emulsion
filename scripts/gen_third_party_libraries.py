#!/usr/bin/env python3
"""Regenerates THIRD_PARTY_LIBRARIES.md: the Rust crates compiled into the app and the npm packages bundled into
its frontend, with the licence each declares. Run from anywhere:  python3 scripts/gen_third_party_libraries.py

Rust: `cargo tree -e normal --target all` (what the app links on any platform; build scripts, dev dependencies and
proc-macros do not ship). npm: the non-dev entries of app/package-lock.json (what Vite bundles).
The hand-written section at the top of the output is the TEXT constant below; edit it there, not in the output."""
import json, re, subprocess, sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "THIRD_PARTY_LIBRARIES.md"

TEXT = """# Third-party libraries

The code libraries that Emulsion is built from, and the licence each one declares. The AI models that ship with the
app are covered separately in [THIRD_PARTY_NOTICES.md](THIRD_PARTY_NOTICES.md). Everything below is open source; the
full licence text of each library is in its own source distribution (the `LICENSE` files next to its code on
crates.io or npm), and the MIT, Apache-2.0 and BSD texts that most of them use are reproduced in
THIRD_PARTY_NOTICES.md.

This file is generated by `scripts/gen_third_party_libraries.py`; do not edit the lists by hand.

## Components with conditions beyond "keep the notice"

| Component | What it is here | Licence | Where its terms are |
| --- | --- | --- | --- |
| LibRaw | Decodes RAW files; compiled into the app as a static library (`app/src-tauri/vendor/rsraw-sys`, patched, see its `PATCH.md`; on Windows a vcpkg build of the same library) | LGPL-2.1 **or** CDDL-1.0, at the user's choice; copyright LibRaw LLC | `app/src-tauri/vendor/rsraw-sys/LibRaw/COPYRIGHT`, `LICENSE.LGPL`, `LICENSE.CDDL` |
| `lensfun` crate | Lens distortion, vignetting and chromatic-aberration correction; a pure-Rust port of Lensfun, compiled into the app | LGPL-3.0-or-later; copyright the Lensfun contributors and David Veszelovszki | crate's `LICENSE-LGPL-3.0`, `LICENSE-GPL-3.0`, `NOTICE` |
| Lensfun lens database | The lens calibration data (XML) the `lensfun` crate embeds and the app reads | CC-BY-SA 3.0 Unported; the Lensfun community | <https://creativecommons.org/licenses/by-sa/3.0/> |
| `cssparser`, `dtoa-short`, `selectors` | CSS parsing, pulled in by Tauri's HTML handling (`tauri-utils`, `wry`) | MPL-2.0 | each crate's `LICENSE` |
| `dyn-eq` | Small helper used by `tract`, the ONNX inference engine | MPL-2.0 | the crate's `LICENSE` |
| `option-ext` | Small helper used by `dirs`, which finds the app-data folder | MPL-2.0 | the crate's `LICENSE` |
| `webpki-root-certs` | Root certificates `reqwest` uses to verify HTTPS when downloading models | CDLA-Permissive-2.0 | the crate's `LICENSE` |
| Vendored `rsraw`, `rsraw-sys` | Safe wrapper and build glue around LibRaw, patched in this repository | MIT (upstream <https://github.com/hexilee/rsraw>) | `app/src-tauri/vendor/*/Cargo.toml` |

The MPL-2.0 files are used unmodified. MPL-2.0 is a file-level licence: changes to those files would have to be published under it, and nothing else in Emulsion is affected.

Emulsion's own code is under the licence in the repository's `LICENSE` file.
"""


def rust_libs():
    out = subprocess.run(
        ["cargo", "tree", "-e", "normal", "--target", "all", "--prefix", "none", "--format", "{p}|{l}"],
        cwd=ROOT / "app" / "src-tauri", capture_output=True, text=True, check=True).stdout
    libs = {}
    for line in out.splitlines():
        line = line.replace(" (*)", "")
        if "(proc-macro)" in line:
            continue
        m = re.match(r"(\S+) v(\S+?)(?: \([^)]*\))?\|(.*)$", line)
        if not m or "emulsion" == m.group(1):
            continue
        name, version, lic = m.groups()
        libs[(name, version)] = lic.strip() or "(none declared)"
    return libs


def npm_libs():
    lock = json.loads((ROOT / "app" / "package-lock.json").read_text())
    libs = {}
    for path, meta in lock.get("packages", {}).items():
        if not path or meta.get("dev") or meta.get("devOptional"):
            continue
        name = path.split("node_modules/")[-1]
        libs[(name, meta.get("version", "?"))] = meta.get("license", "(none declared)")
    return libs


def section(title, libs):
    by_lic = defaultdict(list)
    for (name, version), lic in sorted(libs.items()):
        by_lic[lic].append(f"{name} {version}")
    lines = [f"## {title} ({len(libs)})", ""]
    for lic, items in sorted(by_lic.items(), key=lambda kv: (-len(kv[1]), kv[0])):
        lines += [f"### {lic} ({len(items)})", "", ", ".join(items), ""]
    return "\n".join(lines)


def main():
    text = TEXT + "\n" + section("Rust crates", rust_libs()) + "\n" + section("JavaScript packages", npm_libs())
    OUT.write_text(text.rstrip() + "\n")
    print(f"wrote {OUT} ({len(text.splitlines())} lines)")


if __name__ == "__main__":
    sys.exit(main())
